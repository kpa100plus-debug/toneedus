import assert from 'node:assert/strict';

export async function testSimulations({req, sql, ownerCookie, otherCookie, sourceId, pass}) {
  const realTables=['users','challenges','teasers','settlements','proofs','notifications','challenge_events','audit_logs'];
  const snapshot=()=>JSON.stringify(realTables.map(t=>[t,sql.prepare(`SELECT * FROM ${t} ORDER BY rowid`).all()]));
  const before=snapshot();
  let serial=0;
  const key=()=>`simulation-regression-${++serial}`;
  const create=async(data={})=>req('/api/simulations',{requestId:key(),...data},ownerCookie);
  assert.equal((await req('/api/simulations')).status,401);
  assert.equal((await req('/api/simulations',{requestId:key()})).status,401);
  for(const rewardAmount of [9999,100000001,10000.5,-1,'bad'])assert.equal((await create({rewardAmount})).status,400);
  const created=await create();assert.equal(created.status,201,JSON.stringify(created.body));let s=created.body.simulation;
  assert.equal(s.mode,'SIMULATION');assert.equal(s.actualCharge,0);assert.equal(s.platformFee,10000);assert.equal(s.solverPayout,90000);
  const sid=s.id;
  assert.equal((await req('/api/simulations/'+sid,undefined,otherCookie)).status,403);
  assert.equal((await req('/api/simulations/'+sid,{requestId:key(),revision:s.revision,role:'solver',action:'SUBMIT_TEASERS'},otherCookie)).status,403);
  assert.equal((await req('/api/simulations',undefined,otherCookie)).status,403);
  pass('virtual transactions require login, validate amounts and remain private to their creator');
  const clone=await create({challengeId:sourceId,rewardAmount:10000});
  assert.equal(clone.status,201);assert.equal(clone.body.simulation.rewardAmount,sql.prepare('SELECT reward_amount FROM challenges WHERE id=?').get(sourceId).reward_amount);
  assert.equal((await req('/api/simulations',{requestId:key(),challengeId:sourceId},otherCookie)).status,403);
  const creationId=key();const once=await create({requestId:creationId});const twice=await create({requestId:creationId});
  assert.equal(once.body.simulation.id,twice.body.simulation.id);
  pass('copy uses authorized source values without editing source; creation retry is idempotent');
  async function action(action,role='owner',extra={},expected=200) {
    const r=await req('/api/simulations/'+s.id,{requestId:key(),revision:s.revision,action,role,...extra},ownerCookie);
    assert.equal(r.status,expected,JSON.stringify(r.body));
    if(r.status===200)s=r.body.simulation;
    return r;
  }
  await action('PAY_APPROVE','owner',{},409);
  await action('SUBMIT_TEASERS','owner',{},403);
  const replayId=key();const stale=s.revision;
  await action('SUBMIT_TEASERS','solver',{requestId:replayId});
  assert.equal(s.candidates.length,2);
  const replay=await req('/api/simulations/'+sid,{requestId:replayId,revision:stale,action:'SUBMIT_TEASERS',role:'solver'},ownerCookie);
  assert.equal(replay.body.idempotent,true);assert.equal(replay.body.simulation.revision,s.revision);
  await action('SHORTLIST','owner',{candidateId:s.candidates[0].id,revision:stale},409);
  await action('SHORTLIST','owner',{candidateId:s.candidates[0].id,requestId:replayId},409);
  pass('virtual workflow rejects out-of-order actions, wrong role, stale updates and request reuse');
  for(const c of s.candidates)await action('SHORTLIST','owner',{candidateId:c.id});
  await action('SELECT','owner',{candidateId:s.candidates[0].id});
  assert.equal(s.candidates.filter(c=>c.status==='SELECTED').length,1);
  await action('SELECT','owner',{candidateId:s.candidates[1].id},409);
  await action('SUBMIT_PROOF','solver',{proof:'보상금을 확보하기 전 제출을 요청하는 잘못된 테스트입니다.'},409);
  await action('PAY_FAIL');assert.equal(s.stage,'FUNDING_REQUIRED');assert.equal(s.paymentStatus,'FAILED');
  await action('PAY_CANCEL');assert.equal(s.stage,'FUNDING_REQUIRED');assert.equal(s.paymentStatus,'CANCELLED');
  const approvalKey=key();await action('PAY_APPROVE','owner',{requestId:approvalKey});assert.equal(s.stage,'EXECUTING');
  const approved=s;
  const approveReplay=await req('/api/simulations/'+sid,{requestId:approvalKey,revision:0,action:'PAY_APPROVE',role:'owner'},ownerCookie);
  assert.equal(approveReplay.body.simulation.transactions.filter(t=>t.status==='APPROVED').length,1);
  await action('PAY_APPROVE','owner',{},409);
  pass('two candidates, one finalist, payment failure/cancel/retry and single virtual approval');
  await action('SUBMIT_PROOF','solver',{proof:'짧음'},400);
  await action('SUBMIT_PROOF','solver',{proof:'제작된 가상 결과물과 원본 자료를 제출합니다. 요청된 조건을 모두 충족했습니다.'});
  await action('REVIEW_REJECT');assert.equal(s.stage,'EXECUTING');
  await action('SUBMIT_PROOF','solver',{proof:'보완을 완료하여 결과물을 다시 제출합니다. 수정된 항목과 증빙을 함께 확인해주세요.'});
  await action('PAYOUT_SUCCESS','owner',{},409);
  await action('REVIEW_ACCEPT');assert.equal(s.stage,'SUCCESS');assert.equal(s.payoutStatus,'PROCESSING');
  await action('PAYOUT_FAIL');assert.equal(s.payoutStatus,'FAILED');
  const payoutKey=key();await action('PAYOUT_SUCCESS','owner',{requestId:payoutKey});assert.equal(s.payoutStatus,'PAID');
  assert.equal(s.transactions.at(-1).amount,90000);assert.equal(s.transactions.at(-1).actualCharge,0);
  const payoutReplay=await req('/api/simulations/'+sid,{requestId:payoutKey,revision:0,action:'PAYOUT_SUCCESS',role:'owner'},ownerCookie);
  assert.equal(payoutReplay.body.simulation.transactions.filter(t=>t.status==='PAID').length,1);
  await action('REFUND','owner',{},409);await action('PAYOUT_SUCCESS','owner',{},409);
  assert.equal((await req('/api/simulations/'+sid,undefined,ownerCookie)).body.simulation.payoutStatus,'PAID');
  pass('proof revision, owner review, payout failure/retry and receipt survive reload without double payout');
  s=(await create()).body.simulation;
  await action('SUBMIT_TEASERS','solver');await action('SHORTLIST','owner',{candidateId:s.candidates[0].id});await action('SELECT','owner',{candidateId:s.candidates[0].id});await action('PAY_APPROVE');
  await action('REFUND');assert.equal(s.paymentStatus,'REFUNDED');assert.equal(s.stage,'CANCELLED');assert.equal(s.transactions.at(-1).amount,100000);
  await action('SUBMIT_PROOF','solver',{proof:'취소된 미션에는 제출할 수 없어야 하는 결과 내용입니다.'},409);await action('REFUND','owner',{},409);
  s=(await create()).body.simulation;await action('CANCEL');assert.equal(s.transactions.length,0);
  pass('virtual full refund and pre-payment cancellation are terminal and never charge funds');
  s=(await create()).body.simulation;
  const concurrency=await Promise.all(['CANCEL','SUBMIT_TEASERS'].map((action,i)=>req('/api/simulations/'+s.id,{requestId:key(),revision:s.revision,action,role:i?'solver':'owner'},ownerCookie)));
  assert.deepEqual(concurrency.map(r=>r.status).sort(),[200,409]);
  assert.equal(snapshot(),before);
  pass('concurrent writes cannot both commit; all real member, mission, reputation and finance tables unchanged');
  return approved;
}
